    //% block="Initialiser OLED"
    export function initialiserOLED(): void {
        pins.spiPins(
            DigitalPin.P15,
            DigitalPin.P14,
            DigitalPin.P13
        )
        pins.spiFormat(8, 3)
        pins.spiFrequency(1000000)

        pins.digitalWritePin(CS, 1)
        pins.digitalWritePin(DC, 1)

        pins.digitalWritePin(RST, 0)
        basic.pause(50)
        pins.digitalWritePin(RST, 1)
        basic.pause(100)

        sendCommand(0xAE)
        sendCommand(0x20)
        sendPair(0xA8, 0x7F)
        sendPair(0xD3, 0x60)
        sendPair(0xDC, 0x00)
        sendPair(0xAD, 0x8A)
        sendPair(0xD5, 0x50)
        sendPair(0xD9, 0x22)
        sendPair(0xDB, 0x35)
        sendCommand(0xA0)
        sendCommand(0xC0)
        sendPair(0x81, 0x4F)
        sendCommand(0xA4)
        sendCommand(0xA6)
        sendCommand(0xAF)
        basic.pause(100)

        initialized = true
        effacerOLED()
    }

    //% block="Effacer OLED"
    export function effacerOLED(): void {
        if (!initialized) {
            return
        }
        buffer.fill(0)
        rafraichir()
    }

    //% block="Afficher texte %texte"
    //% texte.defl="Bonjour"
    export function afficherTexte(texte: string): void {
        if (!initialized) {
            return
        }
        buffer.fill(0)
        dessinerTexte(texte, 0, 0, 1)
        rafraichir()
    }

    //% block="Afficher texte %texte à x %x y %y taille %taille"
    //% texte.defl="Bonjour"
    //% x.defl=0 y.defl=0
    //% taille.min=1 taille.max=4 taille.defl=1
    export function afficherTexteEn(texte: string, x: number, y: number, taille: number): void {
        if (!initialized) {
            return
        }
        buffer.fill(0)
        dessinerTexte(texte, x, y, Math.max(1, Math.min(4, taille)))
        rafraichir()
    }
